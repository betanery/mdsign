// Opções comuns de envio (prazo, lembretes, idioma) — mesma regra para envio, modelos e massa.

import { AppError } from "./http.ts";

export type Reminders = { enabled: boolean; firstDays: number; everyDays: number; max: number };

const clamp = (v: unknown, min: number, max: number, fallback: number) =>
  Math.min(Math.max(Number.isFinite(Number(v)) ? Number(v) : fallback, min), max);

/** Prazo AAAA-MM-DD no futuro (o motor usa o fim do dia). */
export function cleanExpiration(value: unknown): string | null {
  if (value == null || value === "") return null;
  const v = String(value);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(v) || new Date(`${v}T23:59:59`) < new Date())
    throw new AppError("invalid_expiration");
  return v;
}

export function cleanReminders(r: Partial<Reminders> | null | undefined): Reminders | undefined {
  if (!r) return undefined;
  return {
    enabled: Boolean(r.enabled),
    firstDays: clamp(r.firstDays, 1, 30, 2),
    everyDays: clamp(r.everyDays, 1, 30, 3),
    max: clamp(r.max, 0, 10, 3),
  };
}

export function cleanLocale(value: unknown, fallback: string): string {
  return ["pt", "en", "es"].includes(String(value)) ? String(value) : fallback;
}

export function cleanMessage(value: unknown): string | null {
  return (
    String(value ?? "")
      .trim()
      .slice(0, 2000) || null
  );
}

